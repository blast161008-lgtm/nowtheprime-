ANTI_AI = """ПИШИ КАК ЖИВОЙ АВТОР, А НЕ КАК ИИ:
- Идея должна звучать так, как её сказал бы друг-креатор: «сними, как ты…», а не «создайте вовлекающий контент».
- Конкретика из жизни автора (его зал, его ученики, его вещи, его фразы), а не абстракции.
- Запрещены слова и обороты: «погрузимся», «магия», «секрет успеха», «ключ к», «вдохновение», «уникальный»,
  «путешествие» (в переносном смысле), «раскроем», «в этом видео», «друзья», «не забудьте подписаться», «невероятный»,
  «откройте для себя», «давайте разберёмся вместе».
- Тексты на экран — короткие, разговорные, со сленгом ниши, как пишет сам автор. Без пафоса и восклицательных цепочек.
- Не выдумывай события, гостей, локации и бюджет, которых у автора нет."""


def niche_key(niche: str | None) -> str | None:
    n = (niche or "").lower()
    for key, words in NICHE_KEYS:
        if any(w in n for w in words):
            return key
    return None


def library(niche: str | None, limit: int = 16) -> str:
    """Форматы под нишу автора (+ универсальные) для промпта."""
    key = niche_key(niche)
    picked = [f for f in FORMATS if key and key in f[5].split(",")]
    picked += [f for f in FORMATS if f[5] == "*" and f not in picked]
    if not key:
        picked += [f for f in FORMATS if f not in picked]
    lines = ["БИБЛИОТЕКА ПРОВЕРЕННЫХ ФОРМАТОВ (то, что реально залетает в 2026):"]
    for i, (fid, name, struct, hook, signal, _, example) in enumerate(picked[:limit], 1):
        lines.append(f"{i}. {name} — {struct}. Хук: {hook}. Работает на: {signal}. Пример: {example}.")
    return "\n".join(lines)


def block(niche: str | None) -> str:
    return "\n\n".join([RULES, library(niche), ANTI_AI])


