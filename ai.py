def reel_intro(meta: dict, caption: str | None, context: str | None, how: str | None = None) -> str:
    how = how or ("Дальше — кадры ролика с отметками времени. Звук ты не слышишь — оценивай по картинке, "
                  "тексту на экране, подписи и данным о звуке, если они есть.")
    fmt = []
    if meta.get("w") and meta.get("h"):
        fmt.append(f"{meta['w']}x{meta['h']}" + (" (вертикальное)" if meta["h"] > meta["w"] else " (НЕ вертикальное!)"))
    fmt.append(f"длина {meta.get('duration')} с")
    if meta.get("fps"):
        fmt.append(f"{meta['fps']:g} fps")
    if not meta.get("has_audio"):
        fmt.append("БЕЗ ЗВУКА")
    elif meta.get("mean_db") is not None:
        fmt.append(f"средняя громкость {meta['mean_db']} dB")
    ctx = f"\nКонтекст об авторе (его Telegram-канал):\n{context}\n" if context else ""
    return f"""Автор прислал рилс/короткое видео ДО публикации (Instagram Reels / TikTok / Shorts) и хочет понять,
залетит ли он и что исправить.
Технически: {', '.join(fmt)}.
Подпись, которую автор планирует: {caption or '— (не указал)'}
{ctx}
{how}
Первые 1.5 секунды — самое важное: там зритель решает, листать дальше или нет."""


